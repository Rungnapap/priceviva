import { chromium } from "/opt/npm-tools/node_modules/playwright/index.mjs";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
let pass = 0, fail = 0; const check = (n, c) => { c ? pass++ : fail++; console.log(c ? "PASS" : "FAIL", n); };
const base = "http://localhost:4321";
await p.goto(base + "/search?q=headphones"); await p.waitForTimeout(500);
const before = await p.locator("main article").count();
await p.goto(base + "/search?q=headphones&max=1000"); await p.waitForTimeout(500);
const t = await p.locator("main").innerText();
check("price filter shows 'x of y' status", /\d+ of \d+ products cost|No products in this price range/.test(t));
check("price filter does not show more products than unfiltered", (await p.locator("main article").count()) <= before);
await p.goto(base + "/search?q=headphones&min=0&max=999999"); await p.waitForTimeout(500);
check("wide price range keeps products", (await p.locator("main article").count()) > 0);
await p.goto(base + "/search?q=headphones"); await p.waitForTimeout(400);
const href = await p.locator("main article a[href^='/product/']").first().getAttribute("href");
await p.goto(base + href); await p.waitForTimeout(600);
const sel = p.locator("label:has-text('Order offers by') select");
check("offer sort control present", (await sel.count()) === 1);
await sel.selectOption("item"); await p.waitForTimeout(200);
check("item-price sort explains it ignores shipping", /Item price ignores shipping/.test(await p.locator("main").innerText()));
const dsel = p.locator("label:has-text('Deliver to') select").first();
await dsel.selectOption("DE"); await p.waitForTimeout(300);
check("inline deliver-to changes the header destination", (await p.locator("header").innerText()).includes("DE"));
check("no page errors", errs.length === 0); if (errs.length) console.log(errs);
console.log(`${pass} passed, ${fail} failed`); await b.close();
